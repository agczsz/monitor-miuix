export function generateDemoMetricsHistory(nodeId: number, hours = 6): MetricsHistoryResponse {
  const pointsCount = 60
  const step = Math.max(60, Math.floor((hours * 3600) / pointsCount / 60) * 60)
  const now = Math.floor(Date.now() / 1000)
  const node = DEMO_NODES.find((item) => item.id === nodeId)
  const memTotal = node?.metrics?.mem_total || node?.mem_total || 8 * 1024 ** 3
  const metrics: NonNullable<MetricsHistoryResponse["metrics"]> = []
  const ping: NonNullable<MetricsHistoryResponse["ping"]> = []
  const totals = new Map<number, { lost: number; samples: number }>()
  const seed = nodeId * 13.7
  const targets = ["电信 CN2 / CT", "联通 9929 / CU", "移动 CMI / CM"]

  for (let i = pointsCount - 1; i >= 0; i--) {
    const ts = now - i * step
    const wave = Math.sin((i + seed) * 0.22) * 12 + Math.cos((i - seed) * 0.45) * 6
    const cpu = Math.max(4, Math.min(96, Math.round((28 + (nodeId % 3) * 14 + wave) * 10) / 10))
    const memPercent = Math.max(15, Math.min(92, 44 + (nodeId % 4) * 9 + wave * 0.35))
    metrics.push({
      ts,
      cpu,
      cpu_max: Math.min(100, cpu + 5),
      mem_used: Math.round(memTotal * memPercent / 100),
      disk_used: Math.round((20 + i * 0.04) * 1024 ** 3),
      net_rx: Math.max(0, Math.round((15 + wave * 0.8 + (nodeId % 3) * 8) * 1024 * 1024)),
      net_tx: Math.max(0, Math.round((22 + wave * 1.1 + (nodeId % 4) * 10) * 1024 * 1024)),
      minutes: Math.max(1, Math.round(step / 60)),
    })
    for (let taskId = 1; taskId <= 3; taskId++) {
      const basePing = nodeId <= 3 ? 36 : nodeId === 4 ? 138 : 168
      const latency = Math.max(1, Math.round((basePing + taskId * 11 + Math.sin(i * (0.3 - taskId * 0.03)) * 5) * 10) / 10)
      const loss = (taskId === 1 && i % 29 === 0) || (taskId === 3 && i % 19 === 0) ? 1 : 0
      ping.push({ task_id: taskId, ts, latency, ...(loss > 0 ? { loss } : {}) })
      const total = totals.get(taskId) ?? { lost: 0, samples: 0 }
      total.lost += loss
      total.samples += 10
      totals.set(taskId, total)
    }
  }

  return {
    metrics,
    ping,
    probes: Object.fromEntries(targets.map((name, index) => [String(index + 1), name])),
    loss: Object.fromEntries([...totals].filter(([, value]) => value.lost > 0).map(([id, value]) => [String(id), value.lost / value.samples * 100])),
    step,
  }
}
